func BuildGameRules(panelKey, title string) []RawTemplateFile {
	key := rawSlug(panelKey, "custom_rule")
	nameKey := key + "_RULE_NAME"
	groupKey := "RULE_GROUP_GAMEPLAY"
	if rawTextLiteral(title) != "" {
		groupKey = key + "_RULE_GROUP"
	}
	content := strings.NewReplacer(
		"${key}", key, "${name_key}", nameKey, "${group_key}", groupKey,
	).Replace(rawGameRulesTmpl)
	locValues := map[string][]rawLocKV{}
	for _, locale := range rawTemplateLocales {
		oc := rawGameRuleOptionCopy[locale]
		name := rawTextLiteral(title)
		if name == "" {
			name = rawGameRuleNames[locale]
		}
		kvs := []rawLocKV{
			{nameKey, name},
			{key + "_OPTION_DEFAULT", oc[0]},
			{key + "_OPTION_DEFAULT_DESC", oc[1]},
			{key + "_OPTION_ALT", oc[2]},
			{key + "_OPTION_ALT_DESC", oc[3]},
		}
		if groupKey != "RULE_GROUP_GAMEPLAY" {
			kvs = append(kvs, rawLocKV{groupKey, name + " — " + rawGameRuleGroupCopy[locale]})
		}
		locValues[locale] = kvs
	}
	out := []RawTemplateFile{{DestPath: "common/game_rules/" + key + "_game_rules.txt", Content: content}}
	return append(out, rawLocalisationCompanions(key+"_game_rules", locValues)...)
}

