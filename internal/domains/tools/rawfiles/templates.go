type RawTemplateFile struct {
	DestPath string
	Content  string
}

var (
	rawSlugRe = regexp.MustCompile(`[^a-z0-9_]+`)
	rawVarRe  = regexp.MustCompile(`[^A-Za-z0-9_.@^]+`)
)

var rawTemplateLocales = []string{"en", "zh", "ru", "de", "es", "fr", "ja", "ko"}

var rawHOI4LanguageDir = map[string]string{
	"en": "english", "zh": "simp_chinese", "ru": "russian", "de": "german",
	"es": "spanish", "fr": "french", "ja": "japanese", "ko": "korean",
}

func rawSlug(raw, fallback string) string {
	s := strings.Trim(rawSlugRe.ReplaceAllString(strings.ToLower(strings.TrimSpace(raw)), "_"), "_")
	if s == "" {
		return fallback
	}
	return s
}

func rawHaganeFileStem(key string) string {
	if strings.HasSuffix(key, "_hagane") {
		return key
	}
	return key + "_hagane"
}

func rawVarToken(raw, fallback string) string {
	s := rawVarRe.ReplaceAllString(strings.TrimSpace(raw), "")
	if s == "" {
		return fallback
	}
	return s
}

func rawTextLiteral(raw string) string {
	out := raw
	for _, ch := range []string{`"`, "{", "}", "[", "]"} {
		out = strings.ReplaceAll(out, ch, "")
	}
	return strings.Join(strings.Fields(out), " ")
}

func rawYMLValue(raw string) string {
	return locout.YmlEscapeValue(raw)
}

type rawLocKV struct{ Key, Val string }

func rawLocalisationCompanions(fileKey string, values map[string][]rawLocKV) []RawTemplateFile {
	safeKey := rawSlug(fileKey, "template")
	lookup := func(locale, key string) (string, bool) {
		for _, kv := range values[locale] {
			if kv.Key == key {
				return kv.Val, true
			}
		}
		return "", false
	}
	english := values["en"]
	var files []RawTemplateFile
	for _, locale := range rawTemplateLocales {
		hoi4Lang := rawHOI4LanguageDir[locale]
		var keys []string
		seen := map[string]bool{}
		for _, kv := range english {
			if !seen[kv.Key] {
				seen[kv.Key] = true
				keys = append(keys, kv.Key)
			}
		}
		for _, kv := range values[locale] {
			if !seen[kv.Key] {
				seen[kv.Key] = true
				keys = append(keys, kv.Key)
			}
		}
		lines := []string{"\uFEFFl_" + hoi4Lang + ":"}
		for _, locKey := range keys {
			text, ok := lookup(locale, locKey)
			if !ok {
				if text, ok = lookup("en", locKey); !ok {
					text = locKey
				}
			}
			lines = append(lines, " "+locKey+`:0 "`+rawYMLValue(text)+`"`)
		}
		files = append(files, RawTemplateFile{
			DestPath: "localisation/" + hoi4Lang + "/" + safeKey + "_l_" + hoi4Lang + ".yml",
			Content:  strings.Join(lines, "\n") + "\n",
		})
	}
	return files
}

