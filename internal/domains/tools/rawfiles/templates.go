type RawTemplateVar struct {
	Key   string `json:"key"`
	Label string `json:"label"`
}

var rawScriptedDefaultTitles = map[string]string{
	"en": "Overview", "zh": "概览", "ru": "Обзор", "de": "Übersicht",
	"es": "Resumen", "fr": "Vue d’ensemble", "ja": "概要", "ko": "개요",
}

