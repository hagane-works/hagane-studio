const FrontendGameSetupDest = "interface/frontendgamesetupview.gui"

func fgsBlocks(entries []*paradox.Entry, key string) []*paradox.Entry {
	wanted := strings.ToLower(key)
	var out []*paradox.Entry
	for _, e := range entries {
		if e.Key != nil && strings.ToLower(*e.Key) == wanted && e.Block != nil {
			out = append(out, e)
		}
	}
	return out
}

func fgsScalars(entries []*paradox.Entry, key string) []*paradox.Entry {
	wanted := strings.ToLower(key)
	var out []*paradox.Entry
	for _, e := range entries {
		if e.Key != nil && strings.ToLower(*e.Key) == wanted && e.Block == nil {
			out = append(out, e)
		}
	}
	return out
}

func fgsNamedBlocks(entries []*paradox.Entry, elementType, name string) []*paradox.Entry {
	var out []*paradox.Entry
	for _, e := range fgsBlocks(entries, elementType) {
		names := fgsScalars(e.Block.Entries, "name")
		if len(names) == 1 && names[0].Scalar.StrValue() == name {
			out = append(out, e)
		}
	}
	return out
}

func fgsOneNamedBlock(entries []*paradox.Entry, elementType, name, errMsg string) (*paradox.Entry, string) {
	matches := fgsNamedBlocks(entries, elementType, name)
	if len(matches) != 1 {
		return nil, errMsg
	}
	return matches[0], ""
}

func fgsSignature(entries []*paradox.Entry, b *strings.Builder) {
	for _, e := range entries {
		b.WriteString("(")
		if e.Key != nil {
			b.WriteString(*e.Key)
		} else {
			b.WriteString("\x00nil")
		}
		b.WriteString("|")
		if e.Op != nil {
			b.WriteString(*e.Op)
		} else {
			b.WriteString("\x00nil")
		}
		b.WriteString("|")
		if e.Block != nil {
			fgsSignature(e.Block.Entries, b)
		} else {
			b.WriteString(e.Scalar.StrValue())
		}
		b.WriteString("|")
		if e.Quoted {
			b.WriteString("q")
		}
		b.WriteString("|")
		if e.Qualifier != nil {
			b.WriteString(*e.Qualifier)
		}
		b.WriteString(")")
	}
}

func fgsSignatureStr(entries []*paradox.Entry) string {
	var b strings.Builder
	fgsSignature(entries, &b)
	return b.String()
}

func fgsPathWidth(text string) (int, bool) {
	block, _, err := paradox.Parse(text)
	if err != nil || block == nil {
		return 0, false
	}
	roots := fgsBlocks(block.Entries, "guiTypes")
	if len(roots) != 1 {
		return 0, false
	}
	scenario := fgsNamedBlocks(roots[0].Block.Entries, "containerWindowType", "gamesetup_scenario_window")
	if len(scenario) != 1 {
		return 0, false
	}
	bookmarks := fgsNamedBlocks(scenario[0].Block.Entries, "containerWindowType", "bookmarks")
	if len(bookmarks) != 1 {
		return 0, false
	}
	grids := fgsNamedBlocks(bookmarks[0].Block.Entries, "gridBoxType", "bookmarks_grid")
	if len(grids) != 1 {
		return 0, false
	}
	slots := fgsBlocks(grids[0].Block.Entries, "slotsize")
	if len(slots) != 1 {
		return 0, false
	}
	widths := fgsScalars(slots[0].Block.Entries, "width")
	if len(widths) != 1 || widths[0].Scalar.Kind != paradox.ScalarInt {
		return 0, false
	}
	return int(widths[0].Scalar.Int.Int64()), true
}

func BuildFrontendGameSetupSlotsize(baseGUIText string, slotWidth int) ([]RawTemplateFile, string) {
	if strings.TrimSpace(baseGUIText) == "" {
		return nil, "complete base GUI text is required"
	}
	width := slotWidth
	if width < 240 {
		width = 240
	}
	if width > 900 {
		width = 900
	}
	block, _, err := paradox.Parse(baseGUIText)
	if err != nil || block == nil {
		return nil, "base GUI text does not parse"
	}
	roots := fgsBlocks(block.Entries, "guiTypes")

	windowCount := 0
	for _, root := range roots {
		for _, e := range root.Block.Entries {
			if e.Key != nil && e.Block != nil {
				windowCount++
			}
		}
	}
	if len(roots) != 1 || windowCount < 2 {
		return nil, "complete base GUI document with guiTypes and multiple windows is required"
	}
	scenario, errMsg := fgsOneNamedBlock(roots[0].Block.Entries, "containerWindowType",
		"gamesetup_scenario_window", "gamesetup_scenario_window must exist exactly once at GUI root")
	if errMsg != "" {
		return nil, errMsg
	}
	bookmarks, errMsg := fgsOneNamedBlock(scenario.Block.Entries, "containerWindowType",
		"bookmarks", "bookmarks must be directly nested under gamesetup_scenario_window")
	if errMsg != "" {
		return nil, errMsg
	}
	grid, errMsg := fgsOneNamedBlock(bookmarks.Block.Entries, "gridBoxType",
		"bookmarks_grid", "bookmarks_grid must be directly nested under bookmarks")
	if errMsg != "" {
		return nil, errMsg
	}
	slots := fgsBlocks(grid.Block.Entries, "slotsize")
	if len(slots) != 1 {
		return nil, "bookmarks_grid must contain exactly one slotsize block"
	}
	widths := fgsScalars(slots[0].Block.Entries, "width")
	heights := fgsScalars(slots[0].Block.Entries, "height")
	if len(widths) != 1 || len(heights) != 1 {
		return nil, "bookmarks_grid slotsize must contain one width and one height"
	}
	widths[0].Scalar = paradox.Scalar{Kind: paradox.ScalarInt, Int: big.NewInt(int64(width))}
	expected := fgsSignatureStr(block.Entries)

	emitted := importsvc.ToScript(block, 0) + "\n"
	reparsed, _, err := paradox.Parse(emitted)
	if err != nil || reparsed == nil {
		return nil, "patched GUI does not parse"
	}
	if fgsSignatureStr(reparsed.Entries) != expected {
		return nil, "patched GUI changed semantics outside the requested AST update"
	}
	if got, ok := fgsPathWidth(emitted); !ok || got != width {
		return nil, "patched GUI does not expose the exact nested bookmark-grid width"
	}
	return []RawTemplateFile{{DestPath: FrontendGameSetupDest, Content: emitted}}, ""
}
