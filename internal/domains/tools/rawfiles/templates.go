func BuildScriptedGuiPanel(panelKey, title string, variables []RawTemplateVar) []RawTemplateFile {
	key := rawSlug(panelKey, "panel")
	fileStem := rawHaganeFileStem(key)
	titleText := rawTextLiteral(title)
	titleKey := key + "_TITLE"
	locValues := map[string][]rawLocKV{}
	for _, locale := range rawTemplateLocales {
		v := titleText
		if v == "" {
			v = rawScriptedDefaultTitles[locale]
		}
		locValues[locale] = append(locValues[locale], rawLocKV{titleKey, v})
	}
	var rows []string
	firstRowY, rowH := 64, 28
	for i, v := range variables {
		varTok := rawVarToken(v.Key, fmt.Sprintf("var_%d", i))
		label := rawTextLiteral(v.Label)
		if label == "" {
			label = varTok
		}
		locKey := fmt.Sprintf("%s_ROW_%d", key, i)
		rows = append(rows, strings.NewReplacer(
			"${key}", key,
			"${i}", fmt.Sprintf("%d", i),
			"${y}", fmt.Sprintf("%d", firstRowY+i*rowH),
			"${loc_key}", locKey,
		).Replace(rawRowTmpl))
		for _, locale := range rawTemplateLocales {
			locValues[locale] = append(locValues[locale],
				rawLocKV{locKey, label + ": [?" + varTok + "|0]"})
		}
	}
	if len(rows) == 0 {
		rows = append(rows, strings.ReplaceAll(rawRowPlaceholder, "${key}", key))
		for _, locale := range rawTemplateLocales {
			locValues[locale] = append(locValues[locale],
				rawLocKV{key + "_ROW_0", rawScriptedExamples[locale] + ": [?your_variable|0]"})
		}
	}
	height := firstRowY + max(1, len(rows))*rowH + 24
	gui := strings.NewReplacer(
		"${key}", key,
		"${height}", fmt.Sprintf("%d", height),
		"${title_key}", titleKey,
		"${rows}", strings.Join(rows, "\n\n"),
	).Replace(rawGUITmpl)
	scripted := strings.ReplaceAll(rawScriptedTmpl, "${key}", key)
	out := []RawTemplateFile{
		{DestPath: "interface/" + fileStem + ".gui", Content: gui},
		{DestPath: "common/scripted_guis/" + fileStem + ".txt", Content: scripted},
	}
	return append(out, rawLocalisationCompanions(key+"_scripted_gui", locValues)...)
}

