describe("formatLocValue", () => {
  it("prints a value the way its loc format asks", () => {
    expect(formatLocValue(24, "G")).toBe("§G24§!");
    expect(formatLocValue(0.42, "1%H")).toBe("§H42.0%§!");
    expect(formatLocValue(130, "G1")).toBe("§G130.0§!");
    expect(formatLocValue(516, ".0")).toBe("516");
    expect(formatLocValue(0.2, "+%0")).toBe("+20%");
    expect(formatLocValue("Axis", "H")).toBe("§HAxis§!");
  });

  it("leaves the colour out when the colour table is empty", () => {
    setReferenceTables({});
    try {
      expect(formatLocValue(24, "G")).toBe("24");
    } finally {
      setReferenceTables(REFERENCE_TABLES);
    }
  });
});

describe("fillLoc", () => {
  it("fills the game's own slots", () => {
    expect(
      fillLoc("You have $COUNT|Y$ Research Slot(s) available.", { COUNT: 5 }),
    ).toBe("You have §Y5§! Research Slot(s) available.");
  });

  it("reads the service's cleaned form, including bare names it is given", () => {
    expect(fillLoc("Shortcut: KEY", { KEY: "£p£" })).toBe("Shortcut: £p£");
    expect(
      fillLoc("Decisions possible to take (AMOUNT|G)\nLIST", {
        AMOUNT: 24,
        LIST: "A\nB",
      }),
    ).toBe("Decisions possible to take (§G24§!)\nA\nB");
  });

  it("turns slots nobody fills back into run-time slots, so the tooltip drops their line", () => {
    const filled = fillLoc(CLEANED.ARMY_EXPERIENCE_DESC);
    expect(filled).toContain("$UNIT_TRAINING_LEVEL|Y$");
    expect(tooltipMarkup({ text: filled }, false)).toBe(
      "As your equipment is used in combat, you gain Army Experience.",
    );
    expect(fillLoc("Owner: {Root.GetName}")).toBe("Owner: [Root.GetName]");
  });

  it("leaves prose in capitals alone", () => {
    expect(fillLoc("NATO and the USA")).toBe("NATO and the USA");
  });
});

