describe("buttonTooltip", () => {
  it("builds a shortcut button's tooltip from the cleaned loc", () => {
    const navy = buttonTooltip(
      node({ name: "navy_button", raw: { shortcut: "p" } }),
      GERMANY,
      CLEANED,
    );
    expect(navy).toEqual({
      text: "§HNavy§!\nSee an overview of your fleets.\n--------------\nShortcut: £p£",
      icons: { p: "P" },
    });
  });

  it("lists the decisions one can take, and nothing more when there are none", () => {
    const decisions = buttonTooltip(
      node({ name: "decisionview_button", raw: { shortcut: "shift+q" } }),
      GERMANY,
      CLEANED,
    );
    expect(decisions?.text).toBe(
      "§HDecisions§!\nTake decisions and react to events that happen to your nation.\n\n" +
        "Decisions possible to take (§G1§!)\nCancel MEFO Bills\n--------------\nShortcut: £shift£+£q£",
    );

    const markupDesc = {
      ...CLEANED,
      TOPBAR_DECISIONVIEW_DESC:
        "Take decisions and react to events that happen to your nation.\n",
    };
    const none = buttonTooltip(
      node({ name: "decisionview_button", raw: { shortcut: "shift+q" } }),
      { tag: "X" },
      markupDesc,
    );
    expect(none?.text).toBe(
      "§HDecisions§!\nTake decisions and react to events that happen to your nation.\n\n--------------\nShortcut: £shift£+£q£",
    );
  });

  it("names the faction and its initiatives on the faction button", () => {
    const faction = buttonTooltip(
      node({ name: "faction_button", raw: { shortcut: "ctrl+q" } }),
      GERMANY,
      CLEANED,
    );
    expect(faction?.text).toBe(
      "§HFaction§!\n§HAxis§!\nManage and shape your Faction\nFaction Initiatives: §H0§!\n--------------\nShortcut: £ctrl£+£q£",
    );
    const alone = buttonTooltip(
      node({ name: "faction_button", raw: { shortcut: "ctrl+q" } }),
      { tag: "SWI" },
      CLEANED,
    );
    expect(alone?.text).toContain(
      "Not in a Faction\nUnlock faction button by creating one",
    );
  });

  it("gives no tooltip when the loc has not arrived", () => {
    expect(
      buttonTooltip(node({ name: "navy_button" }), GERMANY, {}),
    ).toBeNull();
  });
});

describe("topbarTooltips", () => {
  const root = node({
    type: "containerwindowtype",
    name: "topbar",
    children: [
      node({ name: "navy_button", raw: { shortcut: "p" } }),
      node({ type: "containerwindowtype", name: "cp" }),
      node({ type: "containerwindowtype", name: "land" }),
    ],
  });
  const tips = topbarTooltips(root, GERMANY, CLEANED);

  it("puts the start value under command power", () => {
    expect(tips.get("cp")?.text).toBe(
      "§HCommand Power§!\nCommand Power is used for various military operations.\nCurrent Command Power: §G130.0§!",
    );
  });

  it("drops the experience line that needs a running game", () => {
    expect(tooltipMarkup(tips.get("land") ?? null, false)).toBe(
      "§HArmy Experience§!\nAs your equipment is used in combat, you gain Army Experience.",
    );
  });

  it("shows world tension's start value with its header", () => {
    expect(tips.get("threat_button")?.text).toBe(
      "§HWorld Tension§!\n Current value: §H42.0%§!",
    );
    expect(tips.get("threat_value_button")).toBe(tips.get("threat_button"));
  });

  it("gives the fuel box the file estimate: stock, capacity, days to fill", () => {
    expect(tips.get("fuel_icon")?.text).toBe(
      "§HFuel§!\nFuel is generated by your country's excess oil.\nCurrent Fuel: §H297200§!\n" +
        "Fuel Capacity: §H371500§!\nWith current production rate, you will fill your fuel capacity in §G516 days§!",
    );
  });

  it("keeps convoys' explanation for the delayed half", () => {
    expect(tips.get("convoys_count")).toEqual({
      text: "§HConvoys§!",
      delayed: "Convoys are used when importing resources by sea.",
    });
  });

  it("asks for every key it composes from, within one /loc budget per 64", () => {
    for (const key of Object.keys(CLEANED))
      expect(TOPBAR_LOC_KEYS).toContain(key);
    expect(new Set(TOPBAR_LOC_KEYS).size).toBe(TOPBAR_LOC_KEYS.length);
    expect(TOPBAR_LOC_KEYS).toContain("Jan");
  });
});
